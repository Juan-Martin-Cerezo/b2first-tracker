def open_app(p, query="?spx_test=1&spk=sim", args=None, speech_stub=True):
    browser = p.chromium.launch(args=args or [])
    context = browser.new_context(viewport={"width": 1280, "height": 900},
                                  permissions=["microphone"])
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    if speech_stub:
        context.add_init_script(SPEECH_STUB)
    page.goto(URL + "app" + query, wait_until="networkidle")
    login_owner(page, URL)
    page.evaluate("localStorage.setItem('spx_test','1')")
