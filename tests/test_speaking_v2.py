def wait_until(pg, expression, timeout_s, step=100):
    deadline = time.time() + timeout_s
    while time.time() < deadline:
        if pg.evaluate(expression):
            return True
        pg.wait_for_timeout(step)
    return False


def make_wav(path):
    """A modulated tone with speech/silence cycles, for the fake capture device.

    It opens with a second of near-silence on purpose: the worklet calibrates
    its noise floor from ten frames, so a file that starts mid-tone makes the
    threshold unreachable and the VAD never fires.
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    rate = 16000
    frames = bytearray()
    frames += b"\x00\x00" * int(rate * 1.2)
    for _cycle in range(3):
        for i in range(int(rate * 1.2)):
            value = int(0.28 * 32767 * math.sin(2 * math.pi * 220 * i / rate))
            frames += struct.pack("<h", value)
        frames += b"\x00\x00" * int(rate * 0.8)
    with wave.open(path, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        handle.writeframes(bytes(frames))
    return path


