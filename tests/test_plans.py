    st, body, _ = request(APP_URL, "/api/health", method="GET")
    assert st == 200, (st, body)
    health = json.loads(body)
    assert health.get("ok") is True, health
    for leaked in (UID_A, UID_B, code, code.replace("-", "")):
        assert leaked not in body, "health leaked %r: %s" % (leaked, body)
    out["10_health_no_pii"] = sorted(health.keys())

