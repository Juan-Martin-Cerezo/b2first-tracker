    time.sleep(0.3)
    tree = read_tree(DATA_DIR)
    logs = read_log(stdout_path) + read_log(stderr_path)
    compact = code.replace("-", "")
    for needle in (code.encode(), compact.encode(), expired.encode()):
        assert needle not in tree, "a plaintext code reached data/: %r" % needle
        assert needle not in logs, "a plaintext code reached the server log"
    with open(os.path.join(DATA_DIR, "licenses.json"), "r", encoding="utf-8") as f:
        licenses = json.load(f)
    assert licenses, "licenses.json is empty"
    for key, row in licenses.items():
        assert len(key) == 64 and all(c in "0123456789abcdef" for c in key), key
        assert row.get("user_id") is not None, "an issued code was not redeemed: %s" % row
        assert "code" not in row, row
    out["9_no_plaintext_code"] = {"rows": len(licenses)}

